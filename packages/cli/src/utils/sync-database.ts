import { readFile } from "node:fs/promises";
import path from "node:path";
import { pluginDefinitionSchema } from "../../../registry/metadata";
import { readRetainedSchemas } from "./retained-plugin-schemas";
import { preflight } from "./preflight";

const planDatabaseSchemas = async (
  cwd: string,
  installed: readonly string[],
  retainedOverride?: Readonly<Record<string, readonly string[]>>
): Promise<string> => {
  const contributions = await Promise.all(
    installed.map(async (id): Promise<string[]> => {
      const descriptor = `plugins/${id}/chatjs.json`;
      await preflight(cwd, [descriptor]);
      const definition = pluginDefinitionSchema.parse(
        JSON.parse(await readFile(path.join(cwd, descriptor), "utf-8"))
      );
      if (definition.id !== id) {
        throw new Error(`Plugin descriptor ID does not match ${id}.`);
      }
      const schemas = definition.databaseSchemas ?? [];
      for (const schema of schemas) {
        if (!schema.startsWith(`plugins/${id}/`)) {
          throw new Error(
            `Database schema must belong to plugin ${id}: ${schema}`
          );
        }
      }
      await preflight(cwd, schemas);
      await Promise.all(
        schemas.map(async (schema): Promise<void> => {
          await readFile(path.join(cwd, schema), "utf-8");
        })
      );
      return schemas;
    })
  );
  await preflight(cwd, ["composition/generated/installed-database.ts"]);
  const retained = retainedOverride ?? (await readRetainedSchemas(cwd));
  const preserved = Object.entries(retained)
    .filter(([id]) => !installed.includes(id))
    .flatMap(([, files]) => files);
  await preflight(cwd, preserved);
  await Promise.all(
    preserved.map(async (file) => await readFile(path.join(cwd, file)))
  );
  const schemas = [
    ...new Set([...contributions.flat(), ...preserved]),
  ].toSorted();
  return `// Generated by chat-js sync.\nexport const installedDatabaseSchemas: string[] = ${JSON.stringify(schemas.map((schema): string => `./${schema}`))};\n`;
};

export { planDatabaseSchemas };
