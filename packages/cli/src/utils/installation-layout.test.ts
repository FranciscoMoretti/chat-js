import { rejects } from "node:assert/strict";
import { expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { planInstallation } from "./installation-plan";
import { syncPlugins } from "./sync-plugins";
import { syncTools } from "./sync-tools";

test("fresh installation planning does not require the destination to exist", async () => {
  const parent = await mkdtemp(path.join(tmpdir(), "chatjs-fresh-plan-"));
  try {
    const root = path.join(parent, "new-app");
    const plan = await planInstallation(
      root,
      { plugins: [], tools: [] },
      { fresh: true }
    );
    expect(plan.plugins).toEqual([]);
    await rejects(readFile(path.join(root, "package.json")), {
      code: "ENOENT",
    });
  } finally {
    await rm(parent, { recursive: true, force: true });
  }
});

for (const marker of [
  "plugins/mcp/chatjs.json",
  "tools/chatjs/word-count/chatjs.json",
  "lib/ui-slots.tsx",
  "lib/compose-chat.ts",
  "lib/ai/gateway.ts",
  "lib/storage-provider.ts",
  "lib/sandbox/provider.ts",
  "composition/generated/tools.ts",
  "composition/custom/custom-tools.ts",
  "composition/custom/custom-ui.ts",
  ".chatjs/installed-source.json",
  "tools/chatjs/tools.ts",
  "tools/chatjs/custom-tools.ts",
  "tools/chatjs/custom-ui.ts",
  "features/mcp/chatjs.json",
  "features/installed.ts",
]) {
  test(`add and sync reject legacy ${marker} before changing registrations`, async () => {
    const root = await mkdtemp(path.join(tmpdir(), "chatjs-legacy-"));
    try {
      const file = path.join(root, marker);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, "user-owned legacy source");
      await rejects(
        planInstallation(root, { plugins: [], tools: [] }),
        /Legacy ChatJS installation layout/u
      );
      await rejects(syncTools(root), /Legacy ChatJS installation layout/u);
      await rejects(syncPlugins(root), /Legacy ChatJS installation layout/u);
      expect(await readFile(file, "utf-8")).toBe("user-owned legacy source");
      await rejects(readFile(path.join(root, "chatjs/generated/tools.ts")), {
        code: "ENOENT",
      });
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
}

test("old generated behavior is rejected even without custom composition files", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "chatjs-old-exports-"));
  const file = path.join(
    root,
    "chatjs/generated/installed-model-visibility.ts"
  );
  const source =
    "// Generated by chat-js sync.\nexport const useModelVisibility = () => [];\n";
  try {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, source);
    await rejects(syncPlugins(root), /Legacy ChatJS installation layout/u);
    expect(await readFile(file, "utf-8")).toBe(source);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("an application plugins directory without installation descriptors remains application source", async () => {
  const root = await mkdtemp(
    path.join(tmpdir(), "chatjs-application-plugins-")
  );
  try {
    const directory = path.join(root, "plugins/local");
    await mkdir(directory, { recursive: true });
    const file = path.join(directory, "custom.ts");
    await writeFile(file, "export const local = true;\n");
    await syncPlugins(root);
    expect(await readFile(file, "utf-8")).toBe("export const local = true;\n");
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
