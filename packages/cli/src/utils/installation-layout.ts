import { lstat, readdir } from "node:fs/promises";
import path from "node:path";
import { optionalFile } from "./installation-files";
import { preflight } from "./preflight";

const exists = async (file: string): Promise<boolean> => {
  try {
    await lstat(file);
    return true;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return false;
    }
    throw error;
  }
};

// A layout change must never silently generate registrations the app cannot read.
export const assertCurrentInstallationLayout = async (
  cwd: string
): Promise<void> => {
  const legacyDirectories = await Promise.all(
    ["features", "plugins", "tools/chatjs"].map(async (directory) => {
      await preflight(cwd, [`${directory}/.layout-check`]);
      const entries = await readdir(path.join(cwd, directory), {
        withFileTypes: true,
      }).catch((error: unknown) => {
        if (
          error instanceof Error &&
          "code" in error &&
          error.code === "ENOENT"
        ) {
          return [];
        }
        throw error;
      });
      return entries
        .filter((entry) => entry.isDirectory() || entry.isSymbolicLink())
        .map((entry) => `${directory}/${entry.name}/chatjs.json`);
    })
  );
  const markers = [
    "lib/ui-slots.tsx",
    "lib/compose-chat.ts",
    "lib/ai/gateway.ts",
    "lib/storage-provider.ts",
    "lib/sandbox/provider.ts",
    "composition/generated",
    "composition/custom/custom-tools.ts",
    "composition/custom/custom-ui.ts",
    ".chatjs",
    "tools/chatjs/tools.ts",
    "tools/chatjs/ui.ts",
    "tools/chatjs/custom-tools.ts",
    "tools/chatjs/custom-ui.ts",
    "features/installed.ts",
    ...legacyDirectories.flat(),
  ];
  const found = await Promise.all(
    markers.map(async (marker) =>
      (await exists(path.join(cwd, marker))) ? marker : null
    )
  );
  const legacy = found.filter((marker) => marker !== null);
  // Older generated modules exported application behavior instead of installation inputs.
  // Detect this even when an app has deleted its old custom-tools/custom-ui files.
  const oldExports = [
    [
      "installed-auth",
      /export const installedAuth:\s*AuthenticationIntegration\b/u,
    ],
    ["installed-auth-ui", /export (?:const|function) AuthenticationForm\b/u],
    ["installed-signed-out", /export (?:const|function) SignedOutScreen\b/u],
    [
      "installed-navigation",
      /export (?:const|function) handleModifiedNavigation\b/u,
    ],
    [
      "installed-model-visibility",
      /export (?:const|function) useModelVisibility\b/u,
    ],
    ["installed-uploads", /export (?:const|function) attachmentUploads\b/u],
    ["installed-sign-out", /export (?:const|function) signOutWithPlugin\b/u],
    ["tools", /export (?:const|function) tools\b/u],
    ["ui", /export (?:const|function) ui\b/u],
  ] as const;
  const incompatible = await Promise.all(
    oldExports.map(async ([name, pattern]) => {
      const target = `chatjs/generated/${name}.ts`;
      await preflight(cwd, [target]);
      const contents = await optionalFile(path.join(cwd, target));
      const source = contents?.toString("utf-8");
      return source !== undefined &&
        source.startsWith("// Generated by chat-js sync.") &&
        pattern.test(source)
        ? target
        : null;
    })
  );
  legacy.push(...incompatible.filter((target) => target !== null));
  if (legacy.length > 0) {
    throw new Error(
      `Legacy ChatJS installation layout detected: ${legacy.join(", ")}. Before add, sync, or remove, move generated registrations to chatjs/generated and installation metadata/backups from .chatjs to chatjs without overwriting existing files. Move installed infrastructure to chatjs/core and selected provider implementations/configuration to chatjs/providers, updating imports and preserving source receipts. Adopt the current app-owned integrations/ modules and move custom tools/renderers there, plugin implementations/descriptors to chatjs/plugins/<id>, and installed tools/descriptors to chatjs/tools/<id>. Update app imports and plugin descriptors/factories to the current template contract, then remove the old registration files. Existing files were not changed.`
    );
  }
};
