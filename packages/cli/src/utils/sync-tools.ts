const generated =
  "// Generated by chat-js sync. Do not edit. Customize integrations/tools/execution.ts or integrations/tools/ui.ts; inspect ownership with chat-js status.\n";
const DEFINITION_READ_CONCURRENCY = 4;
const hash = (content: string): string =>
  createHash("sha256").update(content).digest("hex");
const readOptional = async (path: string): Promise<string | null> => {
  const content = await optionalFile(path);
  return content?.toString("utf-8") ?? null;
};
const generatedSource = (body: string): string => {
  const normalizedBody = body
    .replace(
      "export interface WorkflowTools {\n\n}",
      "export type WorkflowTools = Record<never, never>;"
    )
    .replace(
      "export const toolAvailability: Record<string, ToolAvailability> = {\n\n};",
      "export const toolAvailability: Record<string, ToolAvailability> = {};"
    )
    .replace(
      "export const documentUi: DocumentUiRegistry = {\n\n};",
      "export const documentUi: DocumentUiRegistry = {};"
    )
    .replace(
      "export const installedDocumentKinds: ReadonlySet<string> = new Set([\n\n]);",
      "export const installedDocumentKinds: ReadonlySet<string> = new Set([]);"
    )
    .replace(";\n\n\nexport const documentUi", ";\n\nexport const documentUi");
  const registrations = generatedRegistrationSource(normalizedBody);
  return `${generated}// Content: ${hash(registrations)}\n${registrations}`;
};
const checkGenerated = (content: string | null, path: string): void => {
  if (!(typeof content === "string" && content !== "")) {
    return;
  }
  const lines = content.split("\n");
  if (
    !content.startsWith("// Generated by chat-js sync.") ||
    lines[1] !== `// Content: ${hash(lines.slice(2).join("\n"))}`
  ) {
    throw new Error(
      `${path} contains custom or legacy registrations. Preserve them in integrations/tools/execution.ts or integrations/tools/ui.ts and remove the old generated index before running chat-js sync.`
    );
  }
};

const selectionSlots = [
  "codeExecution",
  "generateImage",
  "generateVideo",
  "retrieveUrl",
  "webSearch",
] as const;
const registrationsFor = (
  definitions: readonly ReadonlyInput<ToolDefinition>[]
) =>
  definitions.flatMap((item) =>
    item.tools.map((tool) => ({
      ...tool,
      id: item.id,
      key: item.slot ?? tool.toolExport,
      provider: Boolean(item.slot),
    }))
  );

type Registration = ReturnType<typeof registrationsFor>[number];
const registrationKey = (item: Readonly<Pick<Registration, "key">>): string =>
  item.key;

const readToolDefinition = async (
  cwd: string,
  directory: string,
  entryName: string
): Promise<ToolDefinition | null> => {
  const descriptor = `${directory}/${entryName}/chatjs.json`;
  await preflight(cwd, [descriptor]);
  const content = await readOptional(pathModule.join(cwd, descriptor));
  if (!(typeof content === "string" && content !== "")) {
    return null;
  }
  const definition = toolDefinitionSchema.parse(JSON.parse(content));
  if (definition.id !== entryName) {
    throw new Error(
      `Tool descriptor id must match its directory: ${entryName}`
    );
  }
  await preflight(cwd, [
    `${directory}/${entryName}/tool.ts`,
    ...(typeof definition.availabilityExport === "string" &&
    definition.availabilityExport !== ""
      ? [`${directory}/${entryName}/availability.ts`]
      : []),
    ...definition.tools
      .filter((tool) => tool.workflow)
      .map((tool): string => `agent/tools/${tool.toolExport}.ts`),
    ...(definition.documentKind !== undefined ||
    (typeof definition.documentRunExport === "string" &&
      definition.documentRunExport !== "")
      ? [`${directory}/${entryName}/document.tsx`]
      : []),
    ...(definition.tools.some(
      ({ rendererExport }): boolean =>
        typeof rendererExport === "string" && rendererExport !== ""
    )
      ? [`${directory}/${entryName}/renderer.tsx`]
      : []),
  ]);
  const sources = await Promise.allSettled([
    fs.readFile(pathModule.join(cwd, directory, entryName, "tool.ts")),
    ...definition.tools
      .filter((tool) => tool.workflow)
      .map(
        async (tool) =>
          await fs.readFile(
            pathModule.join(cwd, "agent/tools", `${tool.toolExport}.ts`)
          )
      ),
    ...(definition.documentKind !== undefined ||
    (typeof definition.documentRunExport === "string" &&
      definition.documentRunExport !== "")
      ? [
          fs.readFile(
            pathModule.join(cwd, directory, entryName, "document.tsx")
          ),
        ]
      : []),
    ...(definition.tools.some(
      ({ rendererExport }): boolean =>
        typeof rendererExport === "string" && rendererExport !== ""
    )
      ? [
          fs.readFile(
            pathModule.join(cwd, directory, entryName, "renderer.tsx")
          ),
        ]
      : []),
  ]);
  for (const source of sources) {
    if (source.status === "rejected") {
      throw source.reason;
    }
  }
  return definition;
};

const collectDefinitions = async (
  cwd: string,
  directory: string,
  entries: readonly Readonly<Awaited<ReturnType<typeof readdir>>[number]>[]
): Promise<ToolDefinition[]> => {
  const definitions: ToolDefinition[] = [];
  for (const entry of entries) {
    if (entry.isSymbolicLink()) {
      throw new Error(`Tool directories must not be symlinks: ${entry.name}`);
    }
  }
  const directories = entries.filter(
    (entry) => entry.isDirectory() && !entry.name.startsWith("_")
  );
  for (
    let offset = 0;
    offset < directories.length;
    offset += DEFINITION_READ_CONCURRENCY
  ) {
    // oxlint-disable-next-line eslint/no-await-in-loop -- Bound concurrent definition scopes to four and drain their child reads before reporting a source-order error.
    const batch = await Promise.allSettled(
      directories
        .slice(offset, offset + DEFINITION_READ_CONCURRENCY)
        .map(
          async (entry) => await readToolDefinition(cwd, directory, entry.name)
        )
    );
    for (const result of batch) {
      if (result.status === "rejected") {
        throw result.reason;
      }
      const definition = result.value;
      if (definition) {
        const existing = definitions.findIndex(
          (item: ReadonlyInput<ToolDefinition>): boolean =>
            item.id === definition.id
        );
        if (existing !== -1) {
          definitions.splice(existing, 1);
        }
        definitions.push(definition);
      }
    }
  }
  return definitions;
};

const missingPreviousRegistration = (
  previousTools: string | null,
  ids: Readonly<Pick<Set<string>, "has">>,
  entries: readonly { readonly name: string }[]
): string | null => {
  for (const match of (previousTools ?? "").matchAll(
    /from "@\/chatjs\/tools\/(?<id>[a-z][a-z0-9-]*)\/tool"/gu
  )) {
    const { id } = match.groups ?? {};
    if (
      !ids.has(id ?? "") &&
      entries.some((entry): boolean => entry.name === id)
    ) {
      return id ?? "";
    }
  }
  return null;
};

const validateExpected = (
  definitions: readonly ReadonlyInput<ToolDefinition>[],
  expected: readonly ReadonlyInput<ToolDefinition>[]
): void => {
  for (const requested of expected) {
    const installed = definitions.find(
      (item): boolean => item.id === requested.id
    );
    if (!installed || JSON.stringify(installed) !== JSON.stringify(requested)) {
      throw new Error(
        `Installed descriptor does not match requested tool ${requested.id}. Check the registry item's files and overwrite choices.`
      );
    }
  }
};

const validateSelections = (
  definitions: readonly ReadonlyInput<ToolDefinition>[]
): void => {
  for (const slot of selectionSlots) {
    if (definitions.filter((item): boolean => item.slot === slot).length > 1) {
      throw new Error(
        `Only one ${slot} tool can be selected. Remove the previous tool directory before syncing.`
      );
    }
  }
};

const orderedProperties = (
  properties: readonly { readonly key: string; readonly value: string }[]
): string =>
  properties
    .toSorted((leftProperty, rightProperty) => {
      if (leftProperty.key === rightProperty.key) {
        return 0;
      }
      if (leftProperty.key < rightProperty.key) {
        return -1;
      }
      return 1;
    })
    .map(({ key, value }): string => `  ${key}: ${value},`)
    .join("\n");

const registrationImports = (
  entries: readonly {
    readonly id: string;
    readonly name: string;
    readonly alias: string;
  }[],
  file: "tool" | "renderer"
): string => {
  const groups = new Map<string, (typeof entries)[number][]>();
  for (const item of entries) {
    const names = groups.get(item.id) ?? [];
    names.push(item);
    groups.set(item.id, names);
  }
  const imports = [...groups];
  const rendered = imports.map(
    ([id, names]: readonly [
      string,
      readonly (typeof entries)[number][],
    ]): string => {
      const declaration =
        names.length === 1
          ? `import { ${names[0].name} as ${names[0].alias} } from "@/chatjs/tools/${id}/${file}";`
          : `import {\n${names
              .toSorted((left, right): number =>
                left.alias.localeCompare(right.alias)
              )
              .map((name): string => `  ${name.name} as ${name.alias},`)
              .join("\n")}\n} from "@/chatjs/tools/${id}/${file}";`;
      return declaration;
    }
  );
  return rendered.join("\n");
};

const sourceFor = (
  registrations: readonly ReadonlyInput<Registration>[]
): { providerBody: string; toolBody: string; uiBody: string } => {
  const renderers = registrations.filter(
    ({ rendererExport }): boolean =>
      typeof rendererExport === "string" && rendererExport !== ""
  );
  const providers = registrations.filter((item): boolean => item.provider);
  const ordinary = registrations.filter(
    (item): boolean => !item.workflow && !item.provider
  );
  return {
    providerBody: `import { defineToolSet } from "@/lib/eve/tool-types";\n${registrationImports(
      providers.map((item, registrationIndex) => ({
        alias: `tool${registrationIndex}`,
        id: item.id,
        name: item.toolExport,
      })),
      "tool"
    )}\n\nexport const providers = defineToolSet(${providers.length > 0 ? `{\n${orderedProperties(providers.map((item, registrationIndex) => ({ key: registrationKey(item), value: `tool${registrationIndex}` })))}\n}` : "{}"});\n`,
    toolBody: `import { defineToolSet } from "@/lib/eve/tool-types";\n${registrationImports(
      ordinary.map((item, index) => ({
        alias: `tool${index}`,
        id: item.id,
        name: item.toolExport,
      })),
      "tool"
    )}\n\nexport const installedTools = defineToolSet(${ordinary.length > 0 ? `{\n${orderedProperties(ordinary.map((item, index) => ({ key: registrationKey(item), value: `tool${index}` })))}\n}` : "{}"});\n`,
    uiBody: `import type { ToolRendererRegistry } from "@/lib/ai/tool-renderer-registry";\n${registrationImports(
      renderers.flatMap((item, registrationIndex) => {
        if (
          typeof item.rendererExport === "string" &&
          item.rendererExport !== ""
        ) {
          return [
            {
              alias: `renderer${registrationIndex}`,
              id: item.id,
              name: item.rendererExport,
            },
          ];
        }
        return [];
      }),
      "renderer"
    )}\n\nexport const installedToolUi = ${renderers.length > 0 ? `{\n${orderedProperties(renderers.map((item, registrationIndex) => ({ key: JSON.stringify(`tool-${registrationKey(item)}`), value: `renderer${registrationIndex}` })))}\n}` : "{}"} satisfies ToolRendererRegistry;\n`,
  };
};

const validateToolDependencies = (
  definitions: readonly ReadonlyInput<ToolDefinition>[]
): void => {
  const availableKeys = new Set(
    registrationsFor(definitions).map(
      (item: ReadonlyInput<Registration>): string => registrationKey(item)
    )
  );
  for (const definition of definitions) {
    const missingTools = definition.requiresTools.filter(
      (name): boolean => !availableKeys.has(name)
    );
    if (missingTools.length > 0) {
      throw new Error(
        `${definition.id} requires installed tools: ${missingTools.join(", ")}`
      );
    }
  }
  const runners = definitions.filter(
    ({ documentRunExport }) =>
      typeof documentRunExport === "string" && documentRunExport !== ""
  );
  if (runners.length > 1) {
    throw new Error("Only one saved-document executor can be installed.");
  }
  const executor = definitions.find(
    (item): boolean => item.slot === "codeExecution"
  );
  if (
    registrationsFor(definitions).some(
      (item: ReadonlyInput<Registration>): boolean =>
        registrationKey(item) === "runCodeDocument"
    ) &&
    (!executor || (executor.codeExecutorExport ?? "") === "")
  ) {
    throw new Error(
      "Saved code execution requires a compatible codeExecution provider, such as code-execution."
    );
  }
};

const renderToolRegistrations = (
  definitions: readonly ReadonlyInput<ToolDefinition>[],
  configSource: string
): Map<string, string> => {
  const files = new Map<string, string>([
    ["chatjs/generated/installed-config.ts", generatedSource(configSource)],
  ]);
  const documents = definitions.filter(
    (item: ReadonlyInput<ToolDefinition>) => item.documentKind !== undefined
  );
  const registrations = registrationsFor(definitions);
  const keys = registrations.map((item: ReadonlyInput<Registration>): string =>
    registrationKey(item)
  );
  const { providerBody, toolBody, uiBody } = sourceFor(registrations);
  const sharedDefinitions = definitions.flatMap((item) =>
    item.tools.flatMap((tool) =>
      tool.definitionExport === undefined
        ? []
        : [
            {
              id: item.id,
              export: tool.definitionExport,
              name: item.slot ?? tool.toolExport,
            },
          ]
    )
  );
  files.set(
    "chatjs/generated/tool-definitions.ts",
    generatedSource(
      `${sharedDefinitions.map((item, index) => `import { ${item.export} as definition${index} } from "@/chatjs/tools/${item.id}/definition";`).join("\n")}\nexport const installedToolDefinitions = [${sharedDefinitions.map((item, index) => `definition${index} satisfies { readonly name: ${JSON.stringify(item.name)} }`).join(", ")}];\n`
    )
  );

  files.set(
    "chatjs/generated/documents.ts",
    generatedSource(
      `${documents.map((item, index) => `import { documentDefinition as document${index} } from "@/chatjs/tools/${item.id}/definition";`).join("\n")}\nexport const installedDocuments = [${documents.map((item, index) => `document${index} satisfies { readonly kind: ${JSON.stringify(item.documentKind)} }`).join(", ")}];\n`
    )
  );
  files.set(
    "chatjs/generated/document-ui.ts",
    generatedSource(
      `"use client";\n${documents.map((item, index) => `import { documentUi as document${index} } from "@/chatjs/tools/${item.id}/document";`).join("\n")}\nexport const documentUi = [${documents.map((_, index) => `document${index}`).join(", ")}];\n`
    )
  );
  files.set(
    "chatjs/generated/installed-tools.ts",
    generatedSource(
      `export const installedSelectableToolNames: ReadonlySet<string> = new Set(${JSON.stringify(registrations.filter((item) => item.composer).map((item) => item.key))});\nexport const installedWorkflowToolNames: ReadonlySet<string> = new Set(${JSON.stringify(registrations.filter((item) => item.workflow).map((item) => item.key))});\nexport const installedToolNames: ReadonlySet<string> = new Set(${JSON.stringify(keys)});\n`
    )
  );
  const composerTools = registrations
    .filter((item: ReadonlyInput<Registration>) => item.composer)
    .toSorted(
      (
        leftRegistration: ReadonlyInput<Registration>,
        rightRegistration: ReadonlyInput<Registration>
      ): number => leftRegistration.key.localeCompare(rightRegistration.key)
    );
  files.set(
    "chatjs/generated/composer-tools.ts",
    generatedSource(
      `${
        composerTools.length > 0
          ? `import { ${composerTools
              .map((item: ReadonlyInput<Registration>, index) => ({
                alias: `Icon${index}`,
                icon: item.composer?.icon,
              }))
              .toSorted(
                (
                  left: Readonly<{ alias: string; icon: string | undefined }>,
                  right: Readonly<{ alias: string; icon: string | undefined }>
                ): number => left.alias.localeCompare(right.alias)
              )
              .map(
                (
                  item: Readonly<{ alias: string; icon: string | undefined }>
                ): string => `${item.icon} as ${item.alias}`
              )
              .join(", ")} } from "lucide-react";\n`
          : ""
      }import type { LucideIcon } from "lucide-react";\n\nexport const composerTools: Readonly<Record<string, { icon: LucideIcon; name: string; shortName: string } | undefined>> = ${composerTools.length > 0 ? `{\n${composerTools.map((item: ReadonlyInput<Registration>, index): string => `  ${JSON.stringify(item.key)}: { icon: Icon${index}, name: ${JSON.stringify(item.composer?.name)}, shortName: ${JSON.stringify(item.composer?.shortName)} },`).join("\n")}\n}` : "{}"};\n`
    )
  );
  const runner = definitions.find(
    ({ documentRunExport }: ReadonlyInput<ToolDefinition>): boolean =>
      typeof documentRunExport === "string" && documentRunExport !== ""
  );
  files.set(
    "chatjs/generated/document-run.ts",
    generatedSource(
      `"use client";\n\nimport type { ComponentType } from "react";\n\nimport type { DocumentRunProps } from "@/chatjs/core/documents/ui";\n${runner ? `\nimport { ${runner.documentRunExport} as InstalledDocumentRun } from "@/chatjs/tools/${runner.id}/document";\n` : ""}\nexport const DocumentRun: ComponentType<DocumentRunProps> | undefined =\n  ${runner ? "InstalledDocumentRun" : "undefined"};\n`
    )
  );
  files.set("chatjs/generated/providers.ts", generatedSource(providerBody));
  const executor = definitions.find(
    ({ codeExecutorExport }: ReadonlyInput<ToolDefinition>): boolean =>
      typeof codeExecutorExport === "string" && codeExecutorExport !== ""
  );
  files.set(
    "chatjs/generated/code-executor.ts",
    generatedSource(
      `import type { CodeExecutor } from "@/lib/eve/code-executor";\n${executor ? `import { ${executor.codeExecutorExport} as execute } from "@/chatjs/tools/${executor.id}/tool";\n` : ""}\nexport const codeExecutor: CodeExecutor | undefined = ${executor ? "execute" : "undefined"};\n`
    )
  );
  const workflows = registrations.filter(
    (item: ReadonlyInput<Registration>) => item.workflow
  );
  files.set(
    "chatjs/generated/workflow-types.ts",
    generatedSource(
      `${workflows.map((item: ReadonlyInput<Registration>, registrationIndex): string => `import type { ${item.toolExport} as workflow${registrationIndex} } from "@/chatjs/tools/${item.id}/tool";`).join("\n")}\n\nexport interface WorkflowTools {\n${workflows.map((item: ReadonlyInput<Registration>, registrationIndex): string => `  ${item.key}: typeof workflow${registrationIndex};`).join("\n")}\n}\n`
    )
  );
  const availability = definitions.filter(
    ({ availabilityExport }: ReadonlyInput<ToolDefinition>): boolean =>
      typeof availabilityExport === "string" && availabilityExport !== ""
  );
  files.set(
    "chatjs/generated/tool-availability.ts",
    generatedSource(
      `import type { ToolAvailability } from "@/lib/eve/tool-availability";\n${availability.map((item: ReadonlyInput<ToolDefinition>, registrationIndex): string => `import { ${item.availabilityExport} as available${registrationIndex} } from "@/chatjs/tools/${item.id}/availability";`).join("\n")}\n\nexport const toolAvailability: Record<string, ToolAvailability> = {\n${availability.flatMap((item: ReadonlyInput<ToolDefinition>, registrationIndex) => item.tools.map((tool): string => `  ${item.slot ?? tool.toolExport}: available${registrationIndex},`)).join("\n")}\n};\n`
    )
  );
  files.set("chatjs/generated/tools.ts", generatedSource(toolBody));
  files.set("chatjs/generated/ui.ts", generatedSource(uiBody));
  return files;
};

const toolRegistrationTargets = [...renderToolRegistrations([], "").keys()];

const readInstalledTools = async (cwd: string): Promise<ToolDefinition[]> => {
  await assertCurrentInstallationLayout(cwd);
  const directory = "chatjs/tools";
  await preflight(cwd, toolRegistrationTargets);
  const dir = pathModule.join(cwd, directory);
  const entries = await readdir(dir, { withFileTypes: true }).catch(
    (error: unknown) => {
      if (
        error instanceof Error &&
        "code" in error &&
        error.code === "ENOENT"
      ) {
        return [];
      }
      throw error;
    }
  );
  const generatedDir = pathModule.join(cwd, "chatjs/generated");
  const toolsPath = pathModule.join(generatedDir, "tools.ts");
  const previousTools = await readOptional(toolsPath);
  await Promise.all(
    toolRegistrationTargets
      .filter((file) => file.startsWith("chatjs/generated/"))
      .map(async (file): Promise<void> => {
        checkGenerated(await readOptional(pathModule.join(cwd, file)), file);
      })
  );
  const definitions = await collectDefinitions(cwd, directory, entries);
  const ids = new Set(
    definitions.map((item: ReadonlyInput<ToolDefinition>): string => item.id)
  );
  const previousProviders = await readOptional(
    pathModule.join(generatedDir, "providers.ts")
  );
  const previousWorkflows = await readOptional(
    pathModule.join(generatedDir, "workflow-types.ts")
  );
  const missing = missingPreviousRegistration(
    `${previousTools ?? ""}\n${previousProviders ?? ""}\n${previousWorkflows ?? ""}`,
    ids,
    entries
  );
  if (typeof missing === "string" && missing !== "") {
    throw new Error(
      `Missing descriptor for previously registered tool: ${missing}. Restore chatjs.json before syncing.`
    );
  }
  return definitions.toSorted(
    (
      leftDefinition: ReadonlyInput<ToolDefinition>,
      rightDefinition: ReadonlyInput<ToolDefinition>
    ): number => leftDefinition.id.localeCompare(rightDefinition.id)
  );
};

const validateToolInstallation = (
  definitions: readonly ReadonlyInput<ToolDefinition>[]
): void => {
  validateSelections(definitions);
  const documents = definitions.filter(
    (item) => item.documentKind !== undefined
  );
  if (
    new Set(documents.map((item) => item.documentKind)).size !==
    documents.length
  ) {
    throw new Error("Only one bundle per document kind can be installed.");
  }
  const keys = registrationsFor(definitions).map(
    (item: ReadonlyInput<Registration>): string => registrationKey(item)
  );
  if (new Set(keys).size !== keys.length) {
    throw new Error("Duplicate installed tool registration key.");
  }
  validateToolDependencies(definitions);
};
const syncTools = async (
  cwd: string,
  options: {
    readonly checkOnly?: boolean;
    readonly expected?: readonly ReadonlyInput<ToolDefinition>[];
  } = {}
): Promise<ToolDefinition[]> => {
  const definitions = await readInstalledTools(cwd);
  await assertUiCompatibility(cwd, definitions);
  validateExpected(definitions, options.expected ?? []);
  validateToolInstallation(definitions);
  const configSource = await planToolConfig(cwd, definitions);
  const documentFiles = definitions.flatMap((item) =>
    item.documentKind === undefined
      ? []
      : [
          `chatjs/tools/${item.id}/definition.ts`,
          `chatjs/tools/${item.id}/document.tsx`,
        ]
  );
  documentFiles.push(
    ...definitions
      .filter((item) =>
        item.tools.some((tool) => tool.definitionExport !== undefined)
      )
      .map((item) => `chatjs/tools/${item.id}/definition.ts`)
  );
  await preflight(cwd, documentFiles);
  await Promise.all(
    documentFiles.map(async (file): Promise<void> => {
      await fs.readFile(pathModule.join(cwd, file), "utf-8");
    })
  );

  if (options.checkOnly === true) {
    return definitions;
  }
  await writeGeneratedFiles(
    cwd,
    renderToolRegistrations(definitions, configSource)
  );
  return definitions;
};

