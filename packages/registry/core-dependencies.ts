export const selectCoreDependencies = (
  dependencies: Readonly<Record<string, string>>
): Record<string, string> =>
  Object.fromEntries(
    Object.entries(dependencies).filter(([name]) =>
      coreDependencyNames.includes(name)
    )
  );
