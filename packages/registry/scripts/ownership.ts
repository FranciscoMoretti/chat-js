import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";
import { demoInstallation } from "../installation";
import { registry } from "../registry";
import { classifyImport, inventoryFiles } from "../src/file-ownership";
import { installationItems, itemClaims } from "../src/installation-ownership";
import { resolveImports } from "../src/ownership-imports";
import { shouldCopyChatAppFile } from "../../cli/src/helpers/scaffold-content";
import { crossingStatus } from "../src/ownership-policy";
import mirrorManifest from "../mirror-manifest.json";

const root = path.resolve(import.meta.dir, "../../../apps/chat");
const sourceExtension = /\.[cm]?[jt]sx?$/u;
const testFile = /(?:^|\/)(?:tests?|__tests__)\/|\.(?:test|spec|visual|e2e)\./u;
const indent = 2;
const candidates = execFileSync(
  "git",
  ["ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", "."],
  {
    cwd: root,
    encoding: "utf-8",
  }
)
  .split("\0")
  .filter(Boolean);
const presentFiles = await Promise.all(
  candidates.map(async (file) => ({
    file,
    present: await Bun.file(path.join(root, file)).exists(),
  }))
);
const worktreeFiles = presentFiles
  .filter(({ present }) => present)
  .map(({ file }) => file);
const items = installationItems(registry.items, demoInstallation);
const inventory = inventoryFiles(worktreeFiles, items.flatMap(itemClaims));
const config = ts.getParsedCommandLineOfConfigFile(
  path.join(root, "tsconfig.json"),
  {},
  {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
      throw new Error(
        ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")
      );
    },
  }
);
if (!config || config.errors.length > 0) {
  throw new Error("Cannot resolve imports using apps/chat/tsconfig.json");
}
const { options } = config;
const byPath = new Map(inventory.map((file) => [file.path, file]));
const fileRole = (file: string, source: string): string => {
  if (testFile.test(file)) {
    return "test";
  }
  return source.startsWith("// Generated by chat-js sync.") ||
    (mirrorManifest.files.includes(file) && byPath.get(file)?.kind === "core")
    ? "generated"
    : "source";
};
const files = await Promise.all(
  inventory.map(async (file) => {
    const present = await Bun.file(path.join(root, file.path)).exists();
    const source =
      present && sourceExtension.test(file.path)
        ? await readFile(path.join(root, file.path), "utf-8")
        : "";
    const role = fileRole(file.path, source);
    const included =
      shouldCopyChatAppFile(file.path.split("/").join(path.sep)) &&
      !file.path.startsWith("lib/db/migrations/");
    const imports =
      present && role !== "test" && included && source !== ""
        ? resolveImports(file.path, source, root, options)
        : { edges: [], unresolved: [] };
    const crossings = imports.edges.flatMap((edge) => {
      const target = byPath.get(edge.to);
      const rule = target ? classifyImport(file, target) : null;
      return rule && target
        ? [
            {
              ...edge,
              rule,
              status: crossingStatus(file, target, role === "generated", items),
            },
          ]
        : [];
    });
    return {
      ...file,
      present,
      role,
      templateCopyEligible: included,
      crossings,
      unresolvedImports: imports.unresolved,
      unclassifiedImports: imports.edges.filter((edge) => !byPath.has(edge.to)),
    };
  })
);
const sharedTargets = files.filter((file) => file.owners.length > 1);
const missingTargets = files.filter((file) => !file.present);
const crossings = files.flatMap((file) => file.crossings);
const unresolved = files.filter((file) => file.unresolvedImports.length > 0);
const unclassified = files.flatMap((file) => file.unclassifiedImports);
const summary = {
  files: files.length,
  installable: files.filter((file) => file.kind === "installable").length,
  core: files.filter((file) => file.kind === "core").length,
  sharedTargets: sharedTargets.map((file) => ({
    path: file.path,
    owners: file.owners,
  })),
  missingTargets: missingTargets.map((file) => file.path),
  crossings: Object.fromEntries(
    ["core-to-installable", "installable-to-core", "cross-installable"].map(
      (rule) => [rule, crossings.filter((edge) => edge.rule === rule).length]
    )
  ),
  needsReview: crossings.filter((edge) => edge.status === "needs-review")
    .length,
  unresolvedFiles: unresolved.map((file) => file.path),
  unclassifiedImports: unclassified,
};
const result = process.argv.includes("--json")
  ? {
      scope:
        "present tracked and non-ignored untracked reference-app files plus claimed targets; current demo selection; static local imports",
      summary,
      files,
    }
  : {
      summary,
      note: "Crossings require review, not automatic waivers. Use --json for file ownership and import evidence. --check fails on unresolved ownership/import findings.",
    };
process.stdout.write(`${JSON.stringify(result, null, indent)}\n`);
if (
  process.argv.includes("--check") &&
  (sharedTargets.length > 0 ||
    missingTargets.length > 0 ||
    crossings.some((edge) => edge.status === "needs-review") ||
    unresolved.length > 0 ||
    unclassified.length > 0)
) {
  process.exitCode = 1;
}
