import { format } from "oxfmt";
import demoFormatConfig from "../../../apps/chat/oxfmt.config";
import { demoInstallation } from "../installation";
import { generateInstallation } from "./installation-generator";

/** Demo policy stays outside shared generation; consumers keep their own configuration. */
const generateDemo = async (
  options: Readonly<{
    changes?: readonly string[];
    previous?: Readonly<Record<string, string>>;
  }> = {}
): Promise<{ files: Map<string, string>; ownedPaths: readonly string[] }> => {
  const installation = await generateInstallation(demoInstallation, options);
  const excluded = new Set(["lib/ai/models.generated.ts"]);
  const files = new Map(
    [...installation.files].filter(([file]) => !excluded.has(file))
  );
  const results = await Promise.allSettled(
    [...files].map(async ([file, source]) => {
      if (
        source.startsWith("// Generated by chat-js sync.") &&
        source.includes("\n// Content:")
      ) {
        return;
      }
      const result = await format(file, source, demoFormatConfig);
      if (result.errors.length > 0) {
        throw new Error(`Could not format demo source: ${file}`);
      }
      files.set(file, result.code);
    })
  );
  for (const result of results) {
    if (result.status === "rejected") {
      throw result.reason;
    }
  }
  const defaults = files.get("chatjs/providers/gateway-defaults.ts");
  if (defaults !== undefined) {
    files.set(
      "chatjs/providers/gateway-defaults.ts",
      defaults.replace(
        'chat: "openai/gpt-5-mini"',
        'chat: "google/gemini-2.5-flash-lite"'
      )
    );
  }
  return {
    files,
    ownedPaths: installation.ownedPaths.filter((file) => !excluded.has(file)),
  };
};
export { generateDemo };
