// Explicit demo exceptions, scoped to one value/import. Everything else is checked.
const demoSource = (file: string, source: string): string => {
  if (file === "lib/ai/gateway-model-defaults.ts") {
    // Keep the demo's existing chat model rather than the fresh scaffold default.
    return source.replace(
      'chat: "openai/gpt-5-mini"',
      'chat: "google/gemini-2.5-flash-lite"'
    );
  }
  return source;
};

const NO_FORMATTING_ERRORS = 0;
const URL_PATH_PREFIX_WIDTH = 1;

const registryRoot = path.resolve(import.meta.dir, "..");

const demoRoot = path.resolve(registryRoot, "../../apps/chat");

const formatted = async (file: string, content: string): Promise<string> => {
  if (
    content.startsWith("// Generated by chat-js sync.") &&
    content.includes("\n// Content:")
  ) {
    return content;
  }
  const result = await format(file, content, demoFormatConfig);
  if (result.errors.length > NO_FORMATTING_ERRORS) {
    throw new Error(`Could not format demo source: ${file}`);
  }
  return result.code;
};
// Drain sibling formatter work before cleanup or process exit after one failure.
// Native formatter callbacks can otherwise still be pending during teardown.
const settleGeneration = async <Value>(
  pending: readonly Promise<Value>[]
): Promise<Value[]> => {
  const results = await Promise.allSettled(pending);
  const values: Value[] = [];
  for (const result of results) {
    if (result.status === "rejected") {
      throw result.reason;
    }
    values.push(result.value);
  }
  return values;
};

const filesBelow = async (
  directory: string,
  prefix = ""
): Promise<string[]> => {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry: Readonly<(typeof entries)[number]>) => {
      const file = path.posix.join(prefix, entry.name);

      if (entry.isDirectory()) {
        return await filesBelow(path.join(directory, entry.name), file);
      }
      return [file];
    })
  );
  return nested.flat();
};

/**
 * Install canonical sources through the CLI's planner and shadcn transforms.
 * @returns {Promise<{ files: Map<string, string>; ownedPaths: readonly string[] }>} Canonical relative paths and their installed source contents.
 */
const generateDemo = async (
  options: Readonly<{
    changes?: readonly string[];
    previous?: Readonly<Record<string, string>>;
  }> = {}
): Promise<{ files: Map<string, string>; ownedPaths: readonly string[] }> => {
  const temporary = await mkdtemp(path.join(tmpdir(), "chatjs-demo-"));
  let stopServer: (() => void) | undefined;
  try {
    // This source-only registry retains registry dependencies, but omits package
    // installation: the demo already owns its workspace dependency manifest.
    const items = await settleGeneration(
      registry.items.map(
        async (item: ReadonlyInput<(typeof registry.items)[number]>) => {
          const files = await Promise.all(
            (item.files ?? []).map(
              async (
                file: ReadonlyInput<
                  NonNullable<(typeof registry.items)[number]["files"]>[number]
                >
              ) => ({
                ...file,
                content: await readFile(
                  path.join(registryRoot, file.path),
                  "utf-8"
                ),
              })
            )
          );
          const itemMeta: unknown = item.meta;
          const metadata: unknown =
            typeof itemMeta === "object" &&
            itemMeta &&
            "chatjs" in itemMeta &&
            itemMeta.chatjs;
          if (
            typeof metadata === "object" &&
            metadata &&
            "kind" in metadata &&
            (metadata.kind === "tool" || metadata.kind === "plugin")
          ) {
            const target =
              metadata.kind === "tool"
                ? `~/tools/chatjs/${item.name}/chatjs.json`
                : `~/plugins/${item.name}/chatjs.json`;
            files.push({
              content: await formatted(target, JSON.stringify(metadata)),
              path: `${item.name}.json`,
              target,
              type: "registry:file",
            });
          }
          return { ...item, dependencies: [], devDependencies: [], files };
        }
      )
    );
    let incrementalItem:
      | Awaited<ReturnType<typeof planInstallation>>["items"][number]
      | undefined;
    const server = Bun.serve({
      fetch(request: Readonly<Pick<Request, "url">>) {
        const name = new URL(request.url).pathname
          .slice(URL_PATH_PREFIX_WIDTH)
          .replace(/\.json$/u, "");
        const item =
          name === "demo-incremental"
            ? incrementalItem
            : items.find(
                (candidate: ReadonlyInput<(typeof items)[number]>) =>
                  candidate.name === name
              );

        if (item) {
          return Response.json(item);
        }
        return new Response("Not found", { status: 404 });
      },
      hostname: "127.0.0.1",
      port: 0,
    });

    stopServer = (): void => {
      void server.stop(true);
    };
    const parsedComponents: unknown = JSON.parse(
      await readFile(path.join(demoRoot, "components.json"), "utf-8")
    );
    if (
      typeof parsedComponents !== "object" ||
      parsedComponents === null ||
      Array.isArray(parsedComponents)
    ) {
      throw new Error("Demo components.json must contain an object");
    }
    const components = Object.assign(parsedComponents, {
      registries: {
        "@chatjs": `http://127.0.0.1:${server.port}/{name}.json`,
      },
    });
    await mkdir(path.join(temporary, "app"), { recursive: true });
    await Promise.all([
      writeFile(
        path.join(temporary, "components.json"),
        JSON.stringify(components)
      ),
      writeFile(
        path.join(temporary, "package.json"),
        '{"name":"demo-sync","dependencies":{}}'
      ),
      writeFile(
        path.join(temporary, "tsconfig.json"),
        '{"compilerOptions":{"baseUrl":".","paths":{"@/*":["./*"]}}}'
      ),
      writeFile(
        path.join(temporary, "app/globals.css"),
        '@import "tailwindcss";'
      ),
    ]);
    const { gateway, storage, sandbox } = demoInstallation;
    if (!(typeof gateway === "string" && gateway !== "") || !storage) {
      throw new Error("Demo preset requires gateway and storage selections");
    }
    const plan = await planInstallation(temporary, demoInstallation, {
      fresh: true,
    });
    const incrementalFiles = await incrementalPluginFiles({
      changes: options.changes,
      previous: options.previous,
      items: plan.items,
      registryRoot,
    });
    if (incrementalFiles) {
      incrementalItem = {
        name: "demo-incremental",
        type: "registry:item",
        files: incrementalFiles,
        dependencies: [],
        devDependencies: [],
      };
    }
    await installItems(
      incrementalItem ? ["@chatjs/demo-incremental"] : plan.sources,
      temporary,
      true
    );
    if (!incrementalItem) {
      if (typeof sandbox === "string" && sandbox !== "") {
        await configureSandboxProvider(
          temporary,
          await resolveSandbox(sandbox, temporary)
        );
      }

      await configureGatewayProvider(
        temporary,
        await resolveGateway(gateway, temporary)
      );
      await configureStorageProvider(temporary, {
        ...(await resolveStorage(storage.source, temporary)),
        options: storage.options,
      });
      await syncTools(temporary, { expected: plan.expected });
      // Composer/settings ordering is application-owned; never initialize or add UI here.
      await syncPlugins(temporary, {
        expected: plan.plugins.map((plugin) => plugin.id),
      });
    }
    // Narrow application-owned exceptions: model catalog is fetched separately;
    // credentials, dependency manifests, UI order and extension files stay local.
    const excluded = new Set([
      "components.json",
      "composer-controls.ts",
      "settings-items.ts",
      "package.json",
      "tsconfig.json",
      "app/globals.css",
      ".env.example",
      "lib/ai/models.generated.ts",
      "composition/custom/custom-tools.ts",
      "composition/custom/custom-ui.ts",
    ]);
    const installedFiles = await filesBelow(temporary);
    const copies = await settleGeneration(
      installedFiles
        .filter((file) => !excluded.has(file))
        .toSorted()
        .map(async (file) => {
          const content = await readFile(path.join(temporary, file), "utf-8");
          const normalized = await formatted(file, content);
          return [
            file,
            await formatted(file, demoSource(file, normalized)),
          ] as const;
        })
    );
    const output = new Map(
      incrementalItem ? Object.entries(options.previous ?? {}) : []
    );
    for (const [file, content] of copies) {
      output.set(file, content);
    }
    if (options.changes) {
      console.info(
        `[registry-mirror] ${incrementalItem ? "Incremental plugin" : "Full"} generation (${copies.length} outputs)`
      );
    }
    // Registry declarations own installed copies; these generators own only
    // composition indexes and their explicit provider configuration outputs.
    const ownedPaths = [
      ...plan.items.flatMap((item) =>
        (item.files ?? []).map((file) => {
          if (file.target?.startsWith("~/") !== true) {
            throw new Error(
              `Expected explicit app-relative target: ${file.path}`
            );
          }
          return file.target.slice(2);
        })
      ),
      ...[...output.keys()].filter((file) =>
        file.startsWith("composition/generated/")
      ),
      "lib/ai/gateway-model-defaults.ts",
      "lib/storage-options.ts",
      "lib/sandbox/options.ts",
    ].filter((file) => !excluded.has(file));
    return { files: output, ownedPaths };
  } finally {
    if (stopServer) {
      stopServer();
    }
    await fs.rm(temporary, { force: true, recursive: true });
  }
};

export { generateDemo };
