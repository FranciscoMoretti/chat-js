/* oxlint-disable import/no-nodejs-modules -- This code runs on the Node/Bun server or installer and requires the built-in operating-system API. */
import { writeFile } from "node:fs/promises";
/* oxlint-enable import/no-nodejs-modules */

/* oxlint-disable import/no-namespace -- This namespace exposes a generated or compiler API whose members are selected at the call site. */
/* oxlint-disable eslint/sort-imports -- Oxfmt owns deterministic import ordering; preserve its order rather than create a formatter/linter rewrite cycle. */
import * as lucide from "lucide-react";
/* oxlint-enable eslint/sort-imports */
/* oxlint-enable import/no-namespace */

const components = new Set<unknown>(Object.values(lucide.icons));
/* oxlint-disable typescript/prefer-readonly-parameter-types -- This parameter participates in the existing SDK or mutable state contract; recursively readonly types would change assignability or permitted updates. */
// oxlint-disable-next-line typescript/no-unsafe-assignment, typescript/no-unsafe-call -- Reflect all Lucide module exports, including aliases, to generate the exact available icon catalog.
const names = Object.entries(lucide)
  .filter(([, value]) => components.has(value))
  .map(([name]) => name)
  .toSorted();
/* oxlint-enable typescript/prefer-readonly-parameter-types */
/* oxlint-disable node/no-top-level-await -- Module initialization must complete before dependent code consumes the prepared runtime or build artifact. */
await writeFile(
  new URL("../composer-icons.generated.ts", import.meta.url),
  `// Generated by bun scripts/generate-composer-icons.ts. Do not edit.\nexport const composerIconNames: ReadonlySet<string> = new Set(${JSON.stringify(names)});\n`
);
/* oxlint-enable node/no-top-level-await */
